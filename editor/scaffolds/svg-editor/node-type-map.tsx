/** Tag icons for the SVG hierarchy. */

import {
  ALargeSmallIcon,
  BoxIcon,
  CircleDotIcon,
  CircleIcon,
  CodeIcon,
  ComponentIcon,
  CopyIcon,
  CropIcon,
  EyeOffIcon,
  FilterIcon,
  FolderIcon,
  Grid3x3Icon,
  HashIcon,
  HeadingIcon,
  ImageIcon,
  InfoIcon,
  LibraryIcon,
  LinkIcon,
  MinusIcon,
  PaletteIcon,
  PentagonIcon,
  ScissorsIcon,
  ShapesIcon,
  SplineIcon,
  SquareDashedIcon,
  SquareIcon,
  TextIcon,
  TriangleIcon,
  TypeIcon,
} from "lucide-react";
import type { LucideIcon } from "lucide-react";

const ICONS: Readonly<Record<string, LucideIcon>> = {
  svg: SquareDashedIcon,
  g: FolderIcon,
  symbol: ComponentIcon,
  use: CopyIcon,
  a: LinkIcon,
  defs: LibraryIcon,
  rect: SquareIcon,
  circle: CircleIcon,
  ellipse: CircleIcon,
  line: MinusIcon,
  polyline: SplineIcon,
  polygon: PentagonIcon,
  path: SplineIcon,
  text: TypeIcon,
  tspan: ALargeSmallIcon,
  textPath: TextIcon,
  image: ImageIcon,
  linearGradient: PaletteIcon,
  radialGradient: CircleDotIcon,
  stop: HashIcon,
  pattern: Grid3x3Icon,
  clipPath: CropIcon,
  mask: EyeOffIcon,
  filter: FilterIcon,
  marker: TriangleIcon,
  style: PaletteIcon,
  title: HeadingIcon,
  desc: InfoIcon,
  metadata: InfoIcon,
  script: CodeIcon,
  foreignObject: BoxIcon,
  switch: ScissorsIcon,
};

export function tagIcon(tag: string): LucideIcon {
  return Object.hasOwn(ICONS, tag) ? ICONS[tag] : ShapesIcon;
}
